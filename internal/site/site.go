// Package site lays a rendered page tree (package render) out as a static
// HTML site and writes it to the site folder (requirements PT-1, PT-5,
// SB-1..3, CLI-4).
package site

import (
	"bytes"
	"context"
	"embed"
	"errors"
	"fmt"
	"html/template"
	"log/slog"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/rolling-robot/sysml-publisher/internal/render"
	"github.com/rolling-robot/sysml-publisher/internal/tree"
	"github.com/rolling-robot/sysml-publisher/macros"
)

// Marker is the file a generated site folder carries, so a later run knows it
// may replace the folder (CLI-4) without risking a folder the user made.
const Marker = ".sysml-publish"

// LandingTitle is the title of the landing page (PT-5).
const LandingTitle = "Model documentation"

//go:embed assets/*.css
var assets embed.FS

//go:embed page.html.tmpl
var pageTemplate string

var page = template.Must(template.New("page").Parse(pageTemplate))

// Site is a rendered site: file contents by slash-separated path relative to
// the site folder.
type Site struct {
	Files map[string][]byte
	// Warnings are the macros' warnings, each once, in the order first seen,
	// failing macros included (MC-19): "<file>:<line>: <page>: <macro>:
	// <message>".
	Warnings []string
}

// Render renders t (render.Tree) and lays it out as a site (New). logger
// and views are render.Options.Logger and render.Options.Views.
func Render(ctx context.Context, t *tree.Tree, logger *slog.Logger, views macros.Views) (*Site, error) {
	res, err := render.Tree(ctx, t, render.Options{Logger: logger, Views: views})
	if err != nil {
		return nil, err
	}
	return New(res)
}

// New lays out res as a site: a page per page of the tree in its folder
// (PT-1), with the tree as a sidebar on every page (SB-1..3), the landing
// page (PT-5), the stylesheets and Marker. Links between pages are the
// tree's relative ones, so res must be rendered with render.Options.Pages
// nil.
func New(res *render.Result) (*Site, error) {
	s := &Site{Files: map[string][]byte{}}
	for _, w := range res.Warnings {
		s.Warnings = append(s.Warnings, w.String())
	}
	l := &layout{t: res.Tree, pages: res.Pages}
	if err := l.page(s, res.Tree.Root); err != nil {
		return nil, err
	}
	for _, n := range res.Tree.Pages {
		if err := l.page(s, n); err != nil {
			return nil, err
		}
	}
	for _, name := range []string{"asciidoctor.css", "layout.css"} {
		data, err := assets.ReadFile("assets/" + name)
		if err != nil {
			return nil, err
		}
		s.Files["assets/"+name] = data
	}
	s.Files[Marker] = []byte("Generated by sysml-publish; this folder is replaced on every run.\n")
	return s, nil
}

// layout writes the pages of a rendered tree.
type layout struct {
	t     *tree.Tree
	pages map[*tree.Node]*render.Page
}

// file is where node n's page is written.
func file(n *tree.Node) string {
	if n.Dir == "" {
		return "index.html"
	}
	return n.Dir + "/index.html"
}

type navItem struct {
	Title    template.HTML
	Href     string
	Current  bool
	Empty    bool
	Children []navItem
}

type pageView struct {
	TitleHTML, TitleText template.HTML
	QualifiedName        string
	AssetsHref, HomeHref string
	SiteTitle            string
	Landing, Empty       bool
	Own, Inherited       []template.HTML
	Nav                  []navItem
}

func (l *layout) page(s *Site, n *tree.Node) error {
	root := l.t.Root
	v := pageView{
		SiteTitle:  LandingTitle,
		AssetsHref: strings.TrimSuffix(tree.Href(n, root), "index.html") + "assets/",
		HomeHref:   tree.Href(n, root),
		Landing:    n == root,
		Empty:      n != root && !n.Documented(),
		Nav:        l.nav(n, root.Children),
	}
	if n == root {
		t := render.PlainTitle(LandingTitle)
		v.TitleHTML, v.TitleText = t.HTML, t.Text
	} else {
		p := l.pages[n]
		if p == nil {
			return fmt.Errorf("%s was not rendered", n.QualifiedName)
		}
		v.TitleHTML, v.TitleText = p.Title.HTML, p.Title.Text
		v.Own, v.Inherited = p.Own, p.Inherited
	}
	if !v.Landing && !n.Unnamed {
		v.QualifiedName = n.QualifiedName
	}
	var buf bytes.Buffer
	if err := page.Execute(&buf, v); err != nil {
		return fmt.Errorf("rendering %s: %w", file(n), err)
	}
	s.Files[file(n)] = buf.Bytes()
	return nil
}

func (l *layout) nav(current *tree.Node, nodes []*tree.Node) []navItem {
	items := make([]navItem, 0, len(nodes))
	for _, c := range nodes {
		var title template.HTML
		if p := l.pages[c]; p != nil {
			title = p.Title.Text
		}
		items = append(items, navItem{
			Title:    title,
			Href:     tree.Href(current, c),
			Current:  c == current,
			Empty:    !c.Documented(),
			Children: l.nav(current, c.Children),
		})
	}
	return items
}

// Write replaces the site folder dir with s (CLI-4). An existing folder is
// replaced only when it is empty or carries Marker from a previous run.
func (s *Site) Write(dir string) error {
	if err := checkReplaceable(dir); err != nil {
		return err
	}
	if err := os.RemoveAll(dir); err != nil {
		return fmt.Errorf("removing the previous site: %w", err)
	}
	for name, data := range s.Files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// ErrNotASite is returned when the site folder exists, is not empty, and was
// not written by this tool.
var ErrNotASite = errors.New("refusing to replace a folder this tool did not create")

func checkReplaceable(dir string) error {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("reading the site folder: %w", err)
	}
	if len(entries) == 0 {
		return nil
	}
	if _, err := os.Stat(filepath.Join(dir, Marker)); err == nil {
		return nil
	}
	return fmt.Errorf("%w: %s is not empty and has no %s file", ErrNotASite, dir, Marker)
}

// Pages lists the page files of s, sorted; used for reporting.
func (s *Site) Pages() []string {
	var out []string
	for name := range s.Files {
		if path.Base(name) == "index.html" {
			out = append(out, name)
		}
	}
	sort.Strings(out)
	return out
}
