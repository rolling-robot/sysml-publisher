// fakeViews renders the views it has, and records the qualified names it
// is asked for.
type fakeViews struct {
	views map[string]*Rendering
	asked []string
}

func (f *fakeViews) Render(_ context.Context, qn string) (*Rendering, error) {
	f.asked = append(f.asked, qn)
	if r, ok := f.views[qn]; ok {
		return r, nil
	}
	return nil, errors.New("sysml: cannot render " + qn)
}

const testSVG = `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN"
 "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- Generated by graphviz -->
<svg width="10pt" height="10pt" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">
<g id="graph0" class="graph"><g id="node1" class="node"><a xlink:href="#node1"><text fill="url(#grad1)">x</text></a></g></g>
</svg>
`

// setupViews loads testdata/views and registers the macros with views
// rendering them; nil registers no renderer.
func setupViews(t *testing.T, views Views) (*tree.Tree, *asciidoctor.Asciidoctor) {
	t.Helper()
	m, err := model.Folder{Dir: filepath.Join("..", "testdata", "views")}.Load(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { m.Close() })
	tr, err := tree.Build(t.Context(), m)
	if err != nil {
		t.Fatal(err)
	}
	ad, err := asciidoctor.New()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { ad.Close() })
	reg, err := Register(t.Context(), ad, tr.Model.Model, tr, record(t, ad))
	if err != nil {
		t.Fatal(err)
	}
	if views != nil {
		reg.SetViews(views)
	}
	return tr, ad
}

func fixtureViews() *fakeViews {
	return &fakeViews{views: map[string]*Rendering{
		"V::sys::interfaces": {SVG: []byte(testSVG)},
		"V::partsTable": {Table: [][]string{
			{"Element", "Kind"},
			{"V::sys::x", "part"},
			{"<b>&", "a*b*"},
		}},
	}}
}

// sysml-view puts in a diagram as its SVG and a table view as a table, for
// the view its target names (MC-15) or the page's own (MC-21).
func TestView(t *testing.T) {
	views := fixtureViews()
	tr, ad := setupViews(t, views)
	sys := Attributes(pageAt(t, tr, "V/sys").ID)
	table := Attributes(pageAt(t, tr, "V/partsTable").ID)
	other := Attributes(pageAt(t, tr, "V/notAView").ID)
	diagram := `<div class="openblock sysml-view">` + "\n" + `<div class="content">` + "\n" +
		`<svg width="10pt" height="10pt" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">` + "\n" +
		`<g id="sysml-view-0e9f1a3a-graph0" class="graph"><g id="sysml-view-0e9f1a3a-node1" class="node">` +
		`<a xlink:href="#sysml-view-0e9f1a3a-node1"><text fill="url(#sysml-view-0e9f1a3a-grad1)">x</text></a></g></g>` + "\n</svg>\n</div>\n</div>"

	cases := []struct {
		name, src string
		attrs     asciidoctor.Attributes
		want      []string // in the output, in this order
		asked     string
	}{
		{"relative to the page", "sysml-view::interfaces[]", sys, []string{diagram}, "V::sys::interfaces"},
		{"qualified, on another page", "sysml-view::V::sys::interfaces[]", other, []string{diagram}, "V::sys::interfaces"},
		{"no target: the page's view", "sysml-view::[]", table, []string{
			`<table class="tableblock frame-all grid-all stretch sysml-view">`,
			`<th class="tableblock halign-left valign-top">Element</th>`,
			`<td class="tableblock halign-left valign-top"><p class="tableblock">V::sys::x</p></td>`,
			`<td class="tableblock halign-left valign-top"><p class="tableblock">&lt;b&gt;&amp;</p></td>`,
			`<td class="tableblock halign-left valign-top"><p class="tableblock">a*b*</p></td>`,
		}, "V::partsTable"},
		{"title of a table", ".Parts\nsysml-view::partsTable[]", sys, []string{`<caption class="title">Parts</caption>`}, "V::partsTable"},
		{"title of a diagram", ".Wiring\nsysml-view::interfaces[]", sys, []string{
			`<div class="openblock sysml-view">` + "\n" + `<div class="title">Wiring</div>`}, "V::sys::interfaces"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			views.asked = nil
			out, err := ad.Convert(c.src, &asciidoctor.Options{Attributes: c.attrs})
			if err != nil {
				t.Fatal(err)
			}
			rest := out
			for _, w := range c.want {
				i := strings.Index(rest, w)
				if i < 0 {
					t.Fatalf("output %q lacks %q (in order)", out, w)
				}
				rest = rest[i+len(w):]
			}
			if len(views.asked) != 1 || views.asked[0] != c.asked {
				t.Errorf("rendered %q, want [%s]", views.asked, c.asked)
			}
			if ws := *recorded[ad]; len(ws) != 0 {
				t.Errorf("warnings %q", ws)
			}
		})
	}
}

// A converter for another output finds the view's qualified name on the
// block (AttrView), to write the picture its own way.
func TestViewAttribute(t *testing.T) {
	tr, ad := setupViews(t, fixtureViews())
	base, err := ad.BuiltinConverter("xhtml5")
	if err != nil {
		t.Fatal(err)
	}
	conv := asciidoctor.ConverterFunc(func(n asciidoctor.Node, transform string, opts map[string]any) (string, error) {
		if qn, ok := n.Attr(AttrView).(string); ok {
			return `<view of="` + qn + `" as="` + transform + `"/>`, nil
		}
		return base.Convert(n, transform, opts)
	})
	if err := ad.RegisterConverter(conv, &asciidoctor.BackendTraits{Basebackend: "html", HTMLSyntax: "xml"}, "wiki"); err != nil {
		t.Fatal(err)
	}
	out, err := ad.Convert("sysml-view::interfaces[]\n\nsysml-view::partsTable[]",
		&asciidoctor.Options{Backend: "wiki", Attributes: Attributes(pageAt(t, tr, "V/sys").ID)})
	if err != nil {
		t.Fatal(err)
	}
	want := `<view of="V::sys::interfaces" as="open"/>` + "\n" + `<view of="V::partsTable" as="table"/>`
	if !strings.Contains(out, want) {
		t.Errorf("output %q lacks %q", out, want)
	}
}

func TestViewErrors(t *testing.T) {
	tr, ad := setupViews(t, fixtureViews())
	other := Attributes(pageAt(t, tr, "V/notAView").ID)
	cases := []struct{ name, src, want string }{
		{"not a view", "sysml-view::sys[]",
			"V::notAView: sysml-view::sys[]: V::sys is a PartUsage, not a view"},
		{"unknown name", "sysml-view::nothing[]",
			`V::notAView: sysml-view::nothing[]: the model has no element named "nothing"`},
		{"no target, the page is no view", "sysml-view::[]",
			"V::notAView: sysml-view::[]: the page's element V::notAView is a PartUsage, not a view; name a view"},
		{"the renderer fails", "sysml-view::V::sys::unrendered[]",
			"V::notAView: sysml-view::V::sys::unrendered[]: sysml: cannot render V::sys::unrendered"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			mustFail(t, ad, c.src, other, c.want)
		})
	}
}

// Without a renderer the macro fails; the host has to give one.
func TestViewWithoutRenderer(t *testing.T) {
	tr, ad := setupViews(t, nil)
	mustFail(t, ad, "sysml-view::interfaces[]", Attributes(pageAt(t, tr, "V/sys").ID),
		"V::sys: sysml-view::interfaces[]: views are not rendered here (no view renderer)")
}
